#!/bin/bash

# ==============================================================================
# Вайбопедия (Vibopedia) — Автоматический скрипт установки и локального развертывания
# ==============================================================================

set -e

echo "🤖 Начинаем установку Вайбопедии (Vibopedia)..."

# 1. Проверка наличия Node.js
if ! command -v node &> /dev/null; then
    echo "❌ Ошибка: Node.js не установлен! Пожалуйста, установите Node.js (v18+) для продолжения."
    exit 1
fi

NODE_VER=$(node -v)
echo "✅ Найдена версия Node.js: $NODE_VER"

# 2. Создание директории для локального хранилища данных и базы SQLite
echo "📁 Создание директории для локальной базы данных SQLite (./data)..."
mkdir -p ./data

# 3. Установка зависимостей проекта
echo "📦 Установка зависимости приложений и библиотек..."
npm install

# 4. Сборка фронтенда
echo "🔨 Сборка приложения для продакшн..."
npm run build

echo ""
echo "=============================================================================="
echo "🎉 Вайбопедия успешно установлена и готова к запуску!"
echo "База данных SQLite создана в директории: ./data/vibopedia.db"
echo ""
echo "Для запуска в режиме разработки (Dev mode):"
echo "  npm run dev"
echo ""
echo "Для запуска в продакшн-режиме (Production mode):"
echo "  npm start"
echo "=============================================================================="
