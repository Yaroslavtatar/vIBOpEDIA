#!/bin/bash

# ==============================================================================
# Вайбопедия (Vibopedia) — Автоматический скрипт установки и локального развертывания
# ==============================================================================

set -e

echo "🤖 Начинаем установку Вайбопедии (Vibopedia)..."

# 1. Проверка наличия Node.js
if ! command -v node &> /dev/null; then
    echo "❌ Ошибка: Node.js не установлен! Пожалуйста, установите Node.js (v18+) для продолжения."
    exit 1
fi

NODE_VER=$(node -v)
echo "✅ Найдена версия Node.js: $NODE_VER"

# 2. Создание директории для локального хранилища данных и базы SQLite
echo "📁 Создание директории для локальной базы данных SQLite (./data)..."
mkdir -p ./data

# 3. Установка зависимостей проекта
echo "📦 Установка зависимостей приложения..."
if [ -f package-lock.json ]; then
  npm ci || npm install
else
  npm install
fi

# 4. Запуск автоматических тестов верификации сборки
echo "🧪 Запуск тестов проверки сборки..."
npm run test:build

echo ""
echo "=============================================================================="
echo "🎉 Вайбопедия успешно собрана, проверена тестами и готова к запуску!"
echo "База данных SQLite создана в директории: ./data/vibopedia.db"
echo ""
echo "Команды запуска:"
echo "  - Режим разработки:          npm run dev"
echo "  - Продакшн-режим:             npm start"
echo "  - Запуск тестов сборки:       npm test"
echo "  - Сборка и запуск в Docker:   docker compose up -d"
echo "  - Тест сборки в Docker:       docker compose --profile test run --rm vibopedia-test"
echo "=============================================================================="
